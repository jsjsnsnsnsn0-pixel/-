 perform set_config('request.jwt.claims',jsonb_build_object('sub',actor,'role','authenticated')::text,true);
 denied:=false;
 begin perform public.dashboard_monthly_finalize(ph,month,req);exception when raise_exception then if sqlerrm<>'settlement compensation incomplete' then raise;end if;denied:=true;end;
 assert denied,'Diamonds cleared before compensation';
 receipt:=public.dashboard_monthly_save_compensation(ph,month,100,jsonb_build_object(agency::text,20));
 assert receipt->'settlement'->>'status'='ready','Compensation not ready';
 receipt:=public.dashboard_monthly_finalize(ph,month,req);

do $$
declare actor uuid:=gen_random_uuid();host uuid:=gen_random_uuid(); outsider uuid:=gen_random_uuid();
pa bigint; ph bigint; agency bigint; room uuid; event uuid; req uuid:=gen_random_uuid();
month date:=(date_trunc('month',current_date)-interval '1 month')::date; receipt jsonb; denied boolean:=false;
begin
 insert into auth.users(id,email,raw_user_meta_data)values(actor,actor||'@test.invalid','{}'),(host,host||'@test.invalid','{}'),(outsider,outsider||'@test.invalid','{}');
 select public_id into pa from public.profiles where id=actor;
 select public_id into ph from public.profiles where id=host;
 insert into public.admin_roles(user_id,role)values(actor,'owner');
 perform set_config('request.jwt.claims',jsonb_build_object('sub',actor,'role','authenticated')::text,true);
 perform set_config('role','authenticated',true);
 agency:=public.create_agency(pa,'Rollback settlement test');
 room:=public.create_room('Rollback settlement test');
 perform set_config('request.jwt.claims',jsonb_build_object('sub',host,'role','authenticated')::text,true);
 perform public.agency_action(agency,'request',null);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',actor,'role','authenticated')::text,true);
 perform public.agency_action(agency,'accept',ph);
 perform set_config('role','postgres',true);
 insert into public.gift_catalog(id,name,price,is_active,diamond_source_type)values('settlement-test-'||actor,'Settlement fixture',1000,true,'FIXED_GIFT');
 insert into public.gift_events(request_id,sender_id,recipient_id,room_id,gift_id,amount,diamond_source_type,quantity,created_at)
 values(gen_random_uuid(),actor,host,room,'settlement-test-'||actor,1000,'FIXED_GIFT',1,month+interval '1 day') returning id into event;
 insert into public.diamond_lots(user_id,source_type,source_reference,diamonds_amount)values(host,'FIXED_GIFT',event,1000);
